export function bindAppShellElements(root = document) {
  const elements = {};
  for (const [name, id] of Object.entries(ELEMENT_IDS)) {
    let element = null;
    Object.defineProperty(elements, name, {
      enumerable: true,
      get() {
        if (!element?.isConnected) element = root.getElementById(id);
        return element;
      },
    });
  }
  return elements;
}
